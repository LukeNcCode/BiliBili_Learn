export type TranslationKey = keyof (typeof translations)["zh"];

const subjectTranslationKeys: Record<SubjectKey, TranslationKey> = {
  programming: "programming",
  language: "languageSubject",
  math: "math",
  science: "science",
  engineering: "engineering",
  medicine: "medicine",
  law: "law",
  politics: "politics",
  humanities: "humanities",
  business: "business",
  exam: "exam",
  career: "career",
  general: "general",
};

export function translate(
  language: Language,
  key: TranslationKey,
  values?: Record<string, string | number>,
) {
  let text: string = translations[language][key] || translations.zh[key] || key;
  if (values) {
    Object.entries(values).forEach(([name, value]) => {
      text = text.replace(`{${name}}`, String(value));
    });
  }
  return text;
}

export function subjectLabel(language: Language, subject: SubjectKey) {
  return translate(language, subjectTranslationKeys[subject] || "general");
}

export function modeLabel(language: Language, mode: LearningMode) {
  if (mode === "focus") {
    return translate(language, "focusMode");
  }
  if (mode === "explore") {
    return translate(language, "exploreMode");
  }
  return translate(language, "balancedMode");
}
